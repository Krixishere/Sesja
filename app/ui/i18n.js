let CURRENT = "en";

function lang() { return CURRENT; }
function locale() { return (LANGS.find((l) => l.code === CURRENT) || LANGS[1]).locale; }
function setLang(code) { CURRENT = DICT[code] ? code : "en"; }
function detectLang() {
  for (const l of navigator.languages || [navigator.language || "en"]) {
    const c = String(l).slice(0, 2).toLowerCase();
    if (DICT[c]) return c;
  }
  return "en";
}

/* t("klucz", {param}) – zwraca tekst (HTML ze słownika jest zaufany; parametry wstawia th() z escapowaniem) */
function t(key, params = {}) {
  let s = DICT[CURRENT][key] ?? DICT.en[key] ?? key;
  if (typeof s !== "string") s = String(s.other ?? key);
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? params[k] : `{${k}}`));
}

/* liczebniki: tn("clips", 3) -> „3 klipy” */
function tn(key, n) {
  const forms = DICT[CURRENT][key] || DICT.en[key];
  const cat = new Intl.PluralRules(locale()).select(n);
  return String(forms[cat] ?? forms.other).replace("{n}", n);
}

if (typeof module !== "undefined") module.exports = { DICT, LANGS, t, tn, setLang };
